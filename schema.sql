-- Asteroid Tracker schema (PostgreSQL)
-- Safe to re-run: tables and indexes are created only when absent.

-- One row per asteroid: identity + physical properties
CREATE TABLE IF NOT EXISTS asteroids (
    spk_id       BIGINT PRIMARY KEY,           -- JPL SPK-ID, e.g. 2099942 (Apophis)
    full_name    TEXT NOT NULL,                -- e.g. '99942 Apophis (2004 MN4)'
    pdes         TEXT NOT NULL,                -- primary designation, e.g. '99942'
    neo          BOOLEAN NOT NULL DEFAULT false, -- near-Earth object ('Y' in SBDB)
    pha          BOOLEAN NOT NULL DEFAULT false, -- potentially hazardous ('Y' in SBDB)
    moid         DOUBLE PRECISION,             -- min. orbit intersection distance with Earth, AU
    h_mag        DOUBLE PRECISION,             -- absolute magnitude H (used to estimate size)
    diameter_km  DOUBLE PRECISION CHECK (diameter_km IS NULL OR diameter_km > 0),
    albedo       DOUBLE PRECISION CHECK (albedo IS NULL OR albedo BETWEEN 0 AND 1),
    rot_per      DOUBLE PRECISION CHECK (rot_per IS NULL OR rot_per > 0), -- rotation period, hours
    spec_type    TEXT,                         -- spectral class, e.g. 'C', 'S', 'Sq', 'X'
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Orbital elements per asteroid per epoch (keeps history when orbits get refined)
CREATE TABLE IF NOT EXISTS orbital_elements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asteroid_id  BIGINT NOT NULL REFERENCES asteroids (spk_id) ON DELETE CASCADE,
    epoch_jd     DOUBLE PRECISION NOT NULL,    -- epoch of elements, Julian Date (TDB)
    a_au         DOUBLE PRECISION NOT NULL,    -- semi-major axis, AU
    e            DOUBLE PRECISION NOT NULL CHECK (e >= 0),  -- eccentricity
    i_deg        DOUBLE PRECISION NOT NULL,    -- inclination, degrees
    om_deg       DOUBLE PRECISION NOT NULL,    -- longitude of ascending node, degrees
    w_deg        DOUBLE PRECISION NOT NULL,    -- argument of perihelion, degrees
    ma_deg       DOUBLE PRECISION NOT NULL,    -- mean anomaly at epoch, degrees
    CONSTRAINT uq_orbital_elements_asteroid_epoch UNIQUE (asteroid_id, epoch_jd)
);

CREATE INDEX IF NOT EXISTS idx_orbital_elements_latest
    ON orbital_elements (asteroid_id, epoch_jd DESC);

-- Fast filters for the UI
CREATE INDEX IF NOT EXISTS idx_asteroids_pha ON asteroids (pha) WHERE pha;
CREATE INDEX IF NOT EXISTS idx_asteroids_name_lower ON asteroids (lower(full_name));

SELECT count(*), count(*) FILTER (WHERE pha) AS hazardous FROM asteroids;
